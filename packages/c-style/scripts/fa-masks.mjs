// Writes src/styles/coalesce/_fa-masks.scss: Lucide glyphs as CSS mask
// images for the raw `<i class="fa fa-*">` elements Coalesce renders outside
// `v-icon` (row actions, descriptions, the editor's required mark, c-display's
// password toggle). Run after changing the list or upgrading @lucide/vue:
//   node scripts/fa-masks.mjs
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const icons = {
  save: "save",
  edit: "pencil",
  "ellipsis-h": "ellipsis",
  "trash-alt": "trash",
  "info-circle": "info",
  asterisk: "asterisk",
  eye: "eye",
  "eye-slash": "eye-off",
};

const attr = (o) =>
  Object.entries(o)
    .filter(([k]) => k !== "key")
    .map(([k, v]) => `${k}='${v}'`)
    .join(" ");

let out = "// Generated by scripts/fa-masks.mjs from @lucide/vue; do not edit.\n$fa-masks: (\n";
for (const [fa, lucide] of Object.entries(icons)) {
  const { __iconData } = await import(`@lucide/vue/dist/esm/icons/${lucide}.mjs`);
  const body = __iconData.node.map(([tag, a]) => `<${tag} ${attr(a)}/>`).join("");
  const svg = `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 24 24' fill='none' stroke='black' stroke-width='1.5' stroke-linecap='round' stroke-linejoin='round'>${body}</svg>`;
  out += `  '${fa}': url("data:image/svg+xml,${encodeURIComponent(svg).replace(/'/g, "%27")}"),\n`;
}
out += ");\n";
writeFileSync(fileURLToPath(new URL("../src/styles/coalesce/_fa-masks.scss", import.meta.url)), out);
